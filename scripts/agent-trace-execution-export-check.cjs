const { chromium } = require('C:/Users/29504/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright')
const assert = require('node:assert/strict'), fs = require('node:fs')
const output = 'docs/agent-trace-execution-verification'
;(async()=>{
  const browser = await chromium.launch({channel:'msedge',headless:true})
  try {
    const page = await browser.newPage({viewport:{width:1950,height:1326},acceptDownloads:true})
    const errors=[], downloads=[]
    page.on('pageerror',e=>errors.push(e.message))
    page.on('download',d=>downloads.push(d))
    await page.route('**/api/v1/**',r=>r.fulfill({status:503,contentType:'application/json',body:JSON.stringify({code:503,message:'Mock-only verification',data:null})}))
    await page.addInitScript(()=>sessionStorage.setItem('accessToken','local-demo-verification'))
    await page.goto('http://127.0.0.1:1223/compliance/agent-traces?view=execution')
    await page.locator('.at-execution').waitFor()
    await page.locator('.compliance-mode .el-switch').evaluate(el=>{if(!el.classList.contains('is-checked'))el.click()})
    await page.locator('.path-scroll > svg > g').first().waitFor()
    await page.waitForTimeout(400)
    const fonts = await page.evaluate(()=>Object.fromEntries(['.ex-query>label','.ex-query .el-select__selected-item','.ex-query>.el-button','.ex-result'].map(q=>[q,getComputedStyle(document.querySelector(q)).fontSize])))
    assert.deepEqual(Object.values(fonts),['14px','14px','14px','14px'])
    fs.mkdirSync(output,{recursive:true})
    await page.screenshot({path:output+'/compact-query.png',fullPage:true})
    await page.getByRole('button',{name:'导出当前视图',exact:true}).click()
    await page.locator('.ex-export-status .el-progress').waitFor()
    await page.getByRole('button',{name:'下载 agent-trace-view.png',exact:true}).waitFor()
    assert.equal(downloads.length,0,'Generation must not trigger an automatic download')
    assert.match(await page.locator('.ex-export-status').innerText(),/succeeded/)
    assert.equal(await page.locator('.ex-export-status .el-progress').count(),0,'Completed export should hide progress, matching the previous pages')
    const measureStatus=selector=>page.locator(selector).evaluate(el=>{
      const style=getComputedStyle(el),button=getComputedStyle(el.querySelector('button'))
      return {container:Object.fromEntries(['display','alignItems','flexWrap','gap','backgroundColor','color','borderTopWidth','borderRadius','padding','margin','fontSize','fontFamily','wordBreak'].map(k=>[k,style[k]])),button:Object.fromEntries(['fontSize','fontFamily','fontWeight','padding','height','borderRadius','borderTopWidth','borderTopColor','backgroundColor','color'].map(k=>[k,button[k]]))}
    })
    const executionStyle=await measureStatus('.ex-export-status')
    await page.screenshot({path:output+'/export-ready.png',fullPage:true})
    const downloadPromise=page.waitForEvent('download')
    await page.getByRole('button',{name:'下载 agent-trace-view.png',exact:true}).click()
    const download=await downloadPromise
    assert.equal(download.suggestedFilename(),'agent-trace-view.png')
    const file=output+'/execution-export.png'
    await download.saveAs(file)
    assert.equal(fs.readFileSync(file).subarray(0,8).toString('hex'),'89504e470d0a1a0a')
    assert.equal(downloads.length,1)
    await page.getByRole('button',{name:'统计指标',exact:true}).click()
    await page.locator('.ats-statistics').waitFor()
    assert.equal(await page.locator('.ex-export-status').count(),0)
    await page.getByRole('button',{name:'导出当前视图',exact:true}).click()
    await page.locator('.ats-export-status').getByRole('button',{name:/^下载 /}).waitFor()
    assert.equal(await page.locator('.ats-export-status .el-progress').count(),0)
    const statisticsStyle=await measureStatus('.ats-export-status')
    assert.deepEqual(executionStyle,statisticsStyle,'Completed export styling must exactly match the statistics page')
    assert.deepEqual(errors,[])
    fs.writeFileSync(output+'/compact-export-check.json',JSON.stringify({fonts,progressBeforeDownload:true,completedProgressHidden:true,executionStyle,statisticsStyle,validPng:true,downloads:downloads.length,passed:true},null,2))
    console.log('PASS: progress before download, completed bar hidden, agent-trace-view.png valid, completed styling exactly matches statistics; no automatic download.')
  } finally { await browser.close() }
})().catch(e=>{console.error(e);process.exitCode=1})
