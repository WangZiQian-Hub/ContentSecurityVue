const { chromium } = require('C:/Users/29504/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright')
const assert = require('node:assert/strict'), fs = require('node:fs')
const output = 'docs/agent-trace-execution-verification'
;(async()=>{
  const browser = await chromium.launch({channel:'msedge',headless:true})
  try {
    const page = await browser.newPage({viewport:{width:1950,height:1326}}), errors=[]
    page.on('pageerror',e=>errors.push(e.message))
    await page.route('**/api/v1/**',r=>r.fulfill({status:503,contentType:'application/json',body:JSON.stringify({code:503,message:'Mock-only verification',data:null})}))
    await page.addInitScript(()=>sessionStorage.setItem('accessToken','local-demo-verification'))
    await page.goto('http://127.0.0.1:1223/compliance/agent-traces?view=execution&batchId=mock_batch_demo')
    await page.locator('.at-execution').waitFor()
    await page.locator('.compliance-mode .el-switch').evaluate(el=>{if(!el.classList.contains('is-checked'))el.click()})
    const panel=page.locator('.ex-sample-panel'), footer=page.locator('.ex-sample-footer')
    await panel.locator('h3').getByText('样本检索与列表（200）',{exact:true}).waitFor()
    assert.equal(await panel.locator('.ex-sample').count(),6)
    async function contained(){
      const p=await panel.boundingBox(),f=await footer.boundingBox()
      assert.ok(f.x>=p.x&&f.x+f.width<=p.x+p.width+1&&f.y>=p.y&&f.y+f.height<=p.y+p.height-1,'Pagination must stay inside the list panel')
      return {panel:p,footer:f}
    }
    await contained()
    await footer.locator('.btn-next').click()
    await footer.locator('.el-pager li.is-active').filter({hasText:/^2$/}).waitFor()
    assert.match(await panel.locator('h3').innerText(),/（200）/)
    await footer.getByText('34',{exact:true}).click()
    await page.waitForFunction(()=>document.querySelectorAll('.ex-sample-panel .ex-sample').length===2)
    assert.match(await panel.locator('h3').innerText(),/（200）/)
    const search=panel.locator('.ex-search input')
    await search.fill('AUD-0042')
    await panel.locator('h3').getByText('样本检索与列表（1）',{exact:true}).waitFor()
    assert.equal(await panel.locator('.ex-sample').count(),1)
    assert.match(await page.locator('.ex-result').innerText(),/样本规模 200/)
    await search.fill('no_such_sample')
    await panel.locator('h3').getByText('样本检索与列表（0）',{exact:true}).waitFor()
    assert.equal(await panel.locator('.ex-sample').count(),0)
    await contained()
    await search.fill('')
    await panel.locator('h3').getByText('样本检索与列表（200）',{exact:true}).waitFor()
    await panel.getByRole('button',{name:'筛选',exact:true}).click()
    await contained()
    await panel.locator('.ex-sample-scroll .el-select').first().click()
    await page.getByRole('option',{name:'en',exact:true}).click()
    await panel.getByRole('button',{name:'应用筛选',exact:true}).click()
    await panel.locator('h3').getByText('样本检索与列表（100）',{exact:true}).waitFor()
    assert.equal(await panel.getByRole('button',{name:'应用筛选',exact:true}).count(),0)
    assert.equal(await panel.getByRole('button',{name:'筛选',exact:true}).getAttribute('aria-expanded'),'false')
    await panel.getByRole('button',{name:'筛选',exact:true}).click()
    assert.match(await panel.locator('.ex-sample-scroll .el-select').first().innerText(),/en/)
    await panel.locator('.ex-sample-scroll .el-select').first().click()
    await page.getByRole('option',{name:'全部语种',exact:true}).click()
    await panel.getByRole('button',{name:'应用筛选',exact:true}).click()
    await panel.locator('h3').getByText('样本检索与列表（200）',{exact:true}).waitFor()
    assert.equal(await panel.getByRole('button',{name:'应用筛选',exact:true}).count(),0)
    // Reopen/close once to verify the existing filter-toggle interaction too.
    await panel.getByRole('button',{name:'筛选',exact:true}).click()
    await panel.getByRole('button',{name:'筛选',exact:true}).click()
    await page.locator('.path-scroll > svg > g').first().waitFor()
    await page.waitForTimeout(400)
    const bounds=await contained()
    fs.mkdirSync(output,{recursive:true})
    await page.screenshot({path:output+'/samples-total-pagination.png',fullPage:true})
    fs.writeFileSync(output+'/samples-total-pagination-check.json',JSON.stringify({initialTotal:200,lastPageRows:2,filteredTotal:1,emptyTotal:0,bounds,passed:true},null,2))
    assert.deepEqual(errors,[])
    console.log('PASS: counts and contained pagination; applying filters collapses conditions, keeps selected language on reopening, and updates results.')
  } finally {await browser.close()}
})().catch(e=>{console.error(e);process.exitCode=1})
